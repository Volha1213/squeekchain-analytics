import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import Ajv2020 from "ajv/dist/2020";
import addFormats from "ajv-formats";
import standaloneCode from "ajv/dist/standalone";
import { _ } from "ajv/dist/compile/codegen";

// Compile at build time. Gateways may forbid Function()/unsafe-eval.
const ajv = new Ajv2020({ strict: false, validateFormats: true,
  code: { source: true, optimize: true } });
addFormats(ajv);
ajv.addKeyword({ keyword: "uintBits", type: "string", schemaType: "number",
  code(cxt) {
    const bits = Number(cxt.schema);
    if (![64,96,256].includes(bits)) throw new Error("Unknown unsigned integer size");
    const limit = (2n ** BigInt(bits)).toString();
    cxt.fail(_`!/^[0-9]+$/.test(${cxt.data}) || BigInt(${cxt.data}) >= BigInt(${limit})`);
  },
});
function prepare(value: unknown): unknown {
  if (Array.isArray(value)) return value.map(prepare);
  if (value && typeof value === "object") {
    const object = value as Record<string, unknown>;
    const format = typeof object.format === "string" ? /^uint(64|96|256)-decimal$/.exec(object.format) : null;
    return Object.fromEntries(Object.entries(object).map(([k,v]) =>
      format && k === "format" ? ["uintBits", Number(format[1])]
        : [k, k === "additionalProperties" && v === false ? true : prepare(v)]));
  }
  return value;
}
const sources = { pipeline: "status", core: "core", economy: "economy-state",
  settlements: "settlements", stats: "measurement-stats" };
for (const [key,file] of Object.entries(sources)) {
  const schema = JSON.parse(readFileSync(new URL(`../src/lib/schemas/${file}.json`, import.meta.url), "utf8"));
  ajv.addSchema(prepare(schema) as object, key);
}
const output = new URL("../src/lib/generated/", import.meta.url);
mkdirSync(output, { recursive: true });
writeFileSync(new URL("validators.cjs", output),
  "// Generated by scripts/generate-validators.ts; do not edit.\n" +
  standaloneCode(ajv, Object.fromEntries(Object.keys(sources).map(k=>[k,k]))) + "\n");
console.log("Generated five standalone validators (no browser schema compilation).");
